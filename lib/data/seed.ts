/** Build a timeline for a lead from its own history + related records. */
export function timelineFor(leadId: string): TimelineEvent[] {
  const lead = leads.find((l) => l.id === leadId);
  if (!lead) return [];
  const events: TimelineEvent[] = [];
  events.push({ id: `${leadId}-created`, leadId, at: lead.createdAt, kind: "lead_created", label: "Lead created", actor: "System" });
  for (const m of messages.filter((m) => m.leadId === leadId)) {
    events.push({
      id: `tl-${m.id}`,
      leadId,
      at: m.createdAt,
      kind: m.direction === "incoming" ? "message_in" : "message_out",
      label: m.direction === "incoming" ? `Incoming (${m.channel}): ${m.body.slice(0, 40)}` : `Reply (${m.channel}): ${m.body.slice(0, 40)}`,
      actor: m.authorName,
    });
  }
  for (const s of lead.stageHistory) {
    events.push({ id: `tl-stage-${leadId}-${s.stage}`, leadId, at: s.at, kind: "stage_change", label: `Stage → ${s.stage}${s.reason ? ` (${s.reason})` : ""}`, actor: s.by });
  }
  for (const b of bookings.filter((b) => b.leadId === leadId)) {
    events.push({ id: `tl-bk-${b.id}`, leadId, at: b.startAt, kind: "booking", label: `Booking ${b.status} — ${b.branch}`, actor: b.source });
  }
  for (const e of escalations.filter((e) => e.leadId === leadId)) {
    events.push({ id: `tl-esc-${e.id}`, leadId, at: e.createdAt, kind: "escalation", label: `Escalated: ${e.reason} (${e.severity})`, actor: e.raisedBy });
  }
  return events.sort((a, b) => new Date(b.at).getTime() - new Date(a.at).getTime());
}
